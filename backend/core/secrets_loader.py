"""
secrets_loader.py — Secure storage & loading of provider API keys.

Keys are stored in `.johnny/credentials/api_keys.env` (mode 0600, gitignored)
created by the first-run wizard (setup_keys.py) or manually.

Precedence (highest wins):
  1. Real OS environment (export NIM_API_KEY=...)
  2. `.johnny/credentials/api_keys.env`   ← wizard / manual setup
  3. `.env` (pydantic dotenv, non-secret config)

`backend/core/config.py` calls `load_secrets()` before instantiating
Settings, so the backend picks up stored keys on every run — no repeating
the wizard. Values are never logged.
"""

import os
import sys
from pathlib import Path

# Keys we know how to store. Extend this list deliberately only.
SUPPORTED_KEYS = ("NIM_API_KEY", "OPENROUTER_API_KEY", "JOHNNY_API_TOKEN")


def credentials_dir() -> Path:
    override = os.getenv("JOHNNY_HOME")
    if override:
        return Path(override) / "credentials"
    # Check current directory
    local = Path.cwd() / ".johnny" / "credentials"
    if local.exists():
        return local
    # Check backend/.johnny/credentials
    backend_local = Path(__file__).resolve().parent.parent / ".johnny" / "credentials"
    if backend_local.exists():
        return backend_local
    # Check repo root .johnny/credentials
    root_local = Path(__file__).resolve().parent.parent.parent / ".johnny" / "credentials"
    if root_local.exists():
        return root_local
    return local


def credentials_file() -> Path:
    override = os.getenv("JOHNNY_HOME")
    if override:
        return Path(override) / "credentials" / "api_keys.env"
    # First check if backend/.johnny/credentials/api_keys.env exists
    backend_cred = Path(__file__).resolve().parent.parent / ".johnny" / "credentials" / "api_keys.env"
    if backend_cred.exists():
        return backend_cred
    root_cred = Path(__file__).resolve().parent.parent.parent / ".johnny" / "credentials" / "api_keys.env"
    if root_cred.exists():
        return root_cred
    return credentials_dir() / "api_keys.env"


def store_keys(values: dict) -> Path:
    """
    Persist secrets atomically with owner-only permissions.
    Existing values are replaced; other supported keys preserved.
    Returns the credential file path.
    """
    known = {"NIM_API_KEY", "OPENROUTER_API_KEY", "JOHNNY_API_TOKEN",
             "DEEPSEEK_R1_API_KEY"}
    for k in list(values.keys()):
        if k not in known:
            raise ValueError(f"Unsupported secret key '{k}'. Supported: {sorted(known)}")
        if not str(values[k]).strip():
            raise ValueError(f"Empty value for '{k}'.")

    cred_file = credentials_file()
    cred_file.parent.mkdir(parents=True, exist_ok=True)

    # Build full payload, preserving keys not being overwritten
    payload: dict = {}
    if cred_file.exists():
        payload = _parse_env_file(cred_file.read_text(encoding="utf-8"))
    payload.update({k: str(v).strip() for k, v in values.items()})

    ordered = {k: payload[k] for k in known if k in payload}
    # Append unknown-but-existing lines at the end to avoid data loss
    extras = {k: v for k, v in payload.items() if k not in ordered}
    if extras:
        for k, v in extras.items():
            ordered[k] = v

    lines = [
        "#Johnny credential store — generated by setup_keys.py",
        "# Mode 0600, gitignored. NEVER commit this file.",
        "",
    ]
    lines += [f"{k}={v}" for k, v in ordered.items()]
    content = "\n".join(lines) + "\n"

    import tempfile
    fd = os.open(cred_file, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
    finally:
        try:
            os.chmod(cred_file, 0o600)
        except OSError:
            pass
    return cred_file


def load_secrets() -> int:
    """
    Load stored secrets into os.environ WITHOUT overriding values that were
    explicitly exported in the real environment. Returns count of keys loaded.
    Called before Settings() is constructed and never logs values.
    """
    cred_file = credentials_file()
    if not cred_file.exists():
        return 0

    _enforce_owner_only_permissions(cred_file)

    loaded = 0
    for key, value in _parse_env_file(cred_file.read_text(encoding="utf-8")).items():
        if key in os.environ and os.environ[key].strip():
            continue  # real env wins
        os.environ[key] = value
        loaded += 1
    return loaded


def mask_status() -> dict:
    """Secrets that are currently available, MASKED (last 4 chars only)."""
    status = {}
    for key in SUPPORTED_KEYS:
        raw = ""
        cred = credentials_file()
        if cred.exists():
            raw = _parse_env_file(cred.read_text(encoding="utf-8")).get(key, "")
        live = os.environ.get(key, "").strip()
        if live:
            status[key] = {
                "source": "environment" if live and not raw else "credential_file",
                "masked": _mask(live) or live,
                "is_placeholder": raw == "" or raw.startswith("paste-") or live.startswith("paste-"),
            }
        elif raw:
            status[key] = {"source": "credential_file", "masked": _mask(raw), "is_placeholder": False}
        else:
            status[key] = {"source": "missing", "masked": "", "is_placeholder": True}
    return status


def nim_api_key_configured() -> bool:
    """True when a real (non-placeholder) NIM key is available."""
    val = os.environ.get("NIM_API_KEY", "").strip()
    if not val and credentials_file().exists():
        val = _parse_env_file(credentials_file().read_text(encoding="utf-8")).get("NIM_API_KEY", "")
    return bool(val) and not val.startswith("paste-") and val != "nvapi-placeholder"


# ─── internals ──────────────────────────────────────────────────────────────────

def _mask(secret: str) -> str:
    if not secret:
        return ""
    if len(secret) <= 8:
        return "•" * len(secret)
    return secret[:4] + "…•••…" + secret[-4:]


def _parse_env_file(text: str) -> dict:
    result = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        key = key.strip()
        val = val.strip().strip("'\"")
        if val.startswith("Bearer "):
            val = val[7:].strip()
        if key:
            result[key] = val
    return result


def _enforce_owner_only_permissions(path: Path) -> None:
    import stat
    try:
        mode = stat.S_IMODE(os.stat(path).st_mode)
        owner_only = stat.S_IRUSR | stat.S_IWUSR
        has_read = mode & (stat.S_IRGRP | stat.S_IROTH)
        if mode != owner_only or has_read:
            os.chmod(path, 0o600)
            print(f"⚠️  Fixed permissions on {path} (was group/world-readable).",
                  file=sys.stderr)
    except OSError:
        pass
