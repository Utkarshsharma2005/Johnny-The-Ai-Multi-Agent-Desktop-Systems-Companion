
import re
import uuid
from datetime import datetime
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field

class ModelOpinion(BaseModel):
    model_id: str = Field(..., description="ID of the model that generated the response")
    raw_output: str = Field(..., description="Raw output generated by the model")
    confidence: float = Field(default=0.85, ge=0.0, le=1.0, description="Confidence score of model response")
    key_assertions: List[str] = Field(default_factory=list, description="Extracted key assertions/claims")
    execution_time_ms: float = Field(default=0.0, description="Latency in milliseconds")

class EvidenceItem(BaseModel):
    claim: str = Field(..., description="Extracted claim or statement")
    supported_by: List[str] = Field(default_factory=list, description="Model IDs supporting this claim")
    opposed_by: List[str] = Field(default_factory=list, description="Model IDs opposing or conflicting with this claim")
    status: str = Field(default="CONSENSUS", description="CONSENSUS | PARTIAL_AGREEMENT | UNVERIFIED | CONFLICT")
    score: float = Field(default=1.0, description="Weighted evidence score")

class MergedEvidenceReport(BaseModel):
    session_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    query: str = Field(..., description="Original user prompt or deliberation goal")
    strategy_used: str = Field(..., description="ensemble | cascade | multimodal_fusion")
    opinions: List[ModelOpinion] = Field(default_factory=list, description="Raw opinions per model")
    evidence_items: List[EvidenceItem] = Field(default_factory=list, description="Normalized evidence assertions")
    consensus_ratio: float = Field(default=1.0, ge=0.0, le=1.0, description="Ratio of agreed claims")
    conflict_detected: bool = Field(default=False, description="Flag indicating contradictory model assertions")
    synthesized_recommendation: str = Field(..., description="Consolidated final recommendation")
    timestamp: str = Field(default_factory=lambda: datetime.now().isoformat())

# ────────────────────────────────────────────────────────────────────────────────
# Confidence calibration (replaces the old hardcoded 0.85 baseline)
# ────────────────────────────────────────────────────────────────────────────────

def calibrate_confidence(raw_output: str) -> float:
    """
    Lightweight deterministic confidence heuristic based on response quality
    signals: length, structure (lists/steps), and failure markers.
    Failure responses score 0; substantive structured answers score highest.
    """
    if not raw_output:
        return 0.0
    if raw_output.startswith("[FAILED]") or "Vision inspection failed" in raw_output[:60]:
        return 0.0
    base = 0.55
    length_boost = min(1.0, len(raw_output) / 1200.0) * 0.25      # substantive length
    structure_boost = 0.10 if "\n-" in raw_output or "\n1." in raw_output or "\n#" in raw_output else 0.0
    return round(min(0.95, base + length_boost + structure_boost), 2)


class EvidenceMerger:
    """
    Core engine for parsing, normalizing, cross-checking, and merging multi-model outputs into a single evidence report.
    """

    @classmethod
    def parse_assertions(cls, text: str) -> List[str]:
        """
        Extracts key sentence assertions from raw text response.
        """
        lines = [line.strip("- *1234567890.").strip() for line in text.split("\n") if line.strip()]
        assertions = []
        for line in lines:
            if len(line) > 15 and not line.lower().startswith("woof"):
                assertions.append(line)
        if not assertions:
            assertions = [text.strip()]
        return assertions

    @classmethod
    def merge_opinions(
        cls,
        query: str,
        strategy_used: str,
        opinions: List[ModelOpinion]
    ) -> MergedEvidenceReport:
        """
        Merges multiple model opinions into a unified MergedEvidenceReport with consensus ratio and conflict detection.
        """
        if not opinions:
            return MergedEvidenceReport(
                query=query,
                strategy_used=strategy_used,
                opinions=[],
                evidence_items=[],
                consensus_ratio=0.0,
                conflict_detected=False,
                synthesized_recommendation="No model opinions available."
            )

        evidence_map: Dict[str, EvidenceItem] = {}
        all_model_ids = [op.model_id for op in opinions]

        # Populate assertions into evidence map
        for op in opinions:
            assertions = op.key_assertions or cls.parse_assertions(op.raw_output)
            for assertion in assertions:
                key = assertion.lower()
                if key not in evidence_map:
                    evidence_map[key] = EvidenceItem(
                        claim=assertion,
                        supported_by=[op.model_id],
                        opposed_by=[],
                        status="CONSENSUS",
                        score=op.confidence
                    )
                else:
                    if op.model_id not in evidence_map[key].supported_by:
                        evidence_map[key].supported_by.append(op.model_id)
                        evidence_map[key].score = min(1.0, evidence_map[key].score + (op.confidence * 0.2))

        evidence_items = list(evidence_map.values())
        conflict_detected = False
        consensus_count = 0

        for item in evidence_items:
            support_count = len(item.supported_by)
            total_models = len(all_model_ids)

            if total_models > 1:
                if support_count == total_models:
                    item.status = "CONSENSUS"
                    consensus_count += 1
                elif support_count > 1:
                    item.status = "PARTIAL_AGREEMENT"
                    consensus_count += 1
                else:
                    # BUGFIX (hardening): a claim made by only ONE model with no
                    # evidence that anyone disagrees is NOT a CONFLICT.
                    # Cross-checking is inherently list-based here, so absence
                    # of the claim in other outputs is simply no corroboration
                    # — 'UNVERIFIED', tracked with the other models noted as
                    # non-supporters and a discounted score.
                    item.opposed_by = [m for m in all_model_ids if m not in item.supported_by]
                    item.status = "UNVERIFIED"
                    item.score = round(item.score * 0.6, 2)  # confidence discount
            else:
                item.status = "CONSENSUS"
                consensus_count += 1

        total_claims = max(1, len(evidence_items))
        consensus_ratio = round(consensus_count / total_claims, 2)

        # Build synthesized recommendation
        primary_opinion = max(opinions, key=lambda op: op.confidence)
        recommendation_parts = [
            f"Consensus synthesis ({len(opinions)} models consulted via strategy '{strategy_used}'):",
            f"Primary Recommendation (Confidence: {primary_opinion.confidence:.2f} by {primary_opinion.model_id}):",
            primary_opinion.raw_output
        ]

        if conflict_detected:
            recommendation_parts.append("\n⚠️ Note: Genuine conflicts detected across model responses. Review evidence items for details.")
        elif any(i.status == "UNVERIFIED" for i in evidence_items):
            unverified = sum(1 for i in evidence_items if i.status == "UNVERIFIED")
            recommendation_parts.append(
                f"\nℹ️ Note: {unverified} claim(s) were made by only one model and lack cross-model "
                f"support — treat them as UNVERIFIED, not confirmed."
            )

        synthesized_recommendation = "\n\n".join(recommendation_parts)

        return MergedEvidenceReport(
            query=query,
            strategy_used=strategy_used,
            opinions=opinions,
            evidence_items=evidence_items,
            consensus_ratio=consensus_ratio,
            conflict_detected=conflict_detected,
            synthesized_recommendation=synthesized_recommendation
        )
